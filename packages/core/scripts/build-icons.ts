/**
 * Vendors the curated icon subset (src/icons/catalog.ts) into
 * src/icons/data/{brands,glyphs}.ts from the simple-icons and lucide npm
 * packages (dev dependencies only — nothing is loaded at runtime).
 *
 * Run from packages/core:  pnpm build:icons
 * (= node --experimental-strip-types scripts/build-icons.ts)
 *
 * Brands whose simple-icons entry is missing or whose per-icon license isn't on
 * the allowlist are left out; resolveIcon then falls back to the lucide glyph +
 * badge declared in the catalog.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as simpleIcons from 'simple-icons'
import * as lucide from 'lucide/dist/esm/iconsAndAliases.mjs'
import { CATALOG } from '../src/icons/catalog.ts'
import { ICON_ALIASES } from '../src/render/iconAliases.ts'

const here = dirname(fileURLToPath(import.meta.url))
const outDir = join(here, '../src/icons/data')
const docsPath = join(here, '../../../docs/ICONS.md')
const pkg = JSON.parse(readFileSync(join(here, '../package.json'), 'utf8'))
const siVersion: string = pkg.devDependencies['simple-icons']
const lucideVersion: string = pkg.devDependencies.lucide

/** Per-icon licenses (simple-icons `license.type`) we can redistribute inside an MIT repo. */
const ALLOWED = new Set(['CC0-1.0', 'MIT', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'CC-BY-3.0', 'CC-BY-4.0'])

interface SiIcon {
	title: string
	slug: string
	hex: string
	path: string
	source: string
	license?: { type: string; url?: string }
}

const toPascal = (kebab: string) =>
	kebab
		.split(/[-_\s]+/)
		.filter(Boolean)
		.map((p) => p[0].toUpperCase() + p.slice(1))
		.join('')

// ── sanity: unique names/aliases ────────────────────────────────────
const seen = new Map<string, string>()
for (const e of CATALOG) {
	for (const n of [e.name, ...(e.aliases ?? [])]) {
		if (n !== n.toLowerCase() || /\s/.test(n)) throw new Error(`icon name must be lowercase kebab: ${n}`)
		const prev = seen.get(n)
		if (prev && prev !== e.name) throw new Error(`icon name/alias "${n}" used by both ${prev} and ${e.name}`)
		seen.set(n, e.name)
	}
}

// ── brands ──────────────────────────────────────────────────────────
const bySlug = new Map<string, SiIcon>()
for (const v of Object.values(simpleIcons) as unknown[]) {
	const i = v as SiIcon
	if (i && typeof i === 'object' && typeof i.slug === 'string' && typeof i.path === 'string') bySlug.set(i.slug, i)
}

const brands: Record<string, { title: string; hex: string; path: string; license?: string }> = {}
const fallbacks: string[] = []
const attributions: string[] = []
for (const e of CATALOG) {
	if (!e.slug) continue
	const i = bySlug.get(e.slug)
	const lic = i?.license?.type
	if (!i || (lic && !ALLOWED.has(lic))) {
		fallbacks.push(`${e.name} (${!i ? 'not in simple-icons' : `license ${lic}`})`)
		continue
	}
	brands[e.slug] = { title: i.title, hex: i.hex, path: i.path, ...(lic ? { license: lic } : {}) }
	if (lic && lic !== 'CC0-1.0') attributions.push(`${i.title}: ${lic}${i.license?.url ? ` (${i.license.url})` : ''}, source ${i.source}`)
}

// ── glyphs ──────────────────────────────────────────────────────────
type Node = [string, Record<string, string | number>][]
const table = lucide as unknown as Record<string, Node>
const glyphNames = new Set<string>([...CATALOG.map((e) => e.glyph), ...Object.values(ICON_ALIASES)])
const glyphs: Record<string, Node> = {}
for (const g of [...glyphNames].sort()) {
	const node = table[toPascal(g)]
	if (!node) throw new Error(`lucide has no icon "${g}"`)
	glyphs[g] = node.map(([tag, a]) => {
		const clean: Record<string, string | number> = {}
		for (const [k, v] of Object.entries(a)) if (k !== 'key') clean[k] = v
		return [tag, clean]
	})
}

// ── write ───────────────────────────────────────────────────────────
const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const objLit = (o: Record<string, string | number>) => `{ ${Object.entries(o).map(([k, v]) => `${/^[a-z]\w*$/i.test(k) ? k : q(k)}: ${typeof v === 'number' ? v : q(v)}`).join(', ')} }`

const brandsTs = `// GENERATED by scripts/build-icons.ts from simple-icons@${siVersion} — do not edit.
// Simple Icons is CC0-1.0 (https://github.com/simple-icons/simple-icons/blob/develop/LICENSE.md).
// Individual logos may carry their own license (\`license\` below; see NOTICE) and
// remain trademarks of their owners: https://github.com/simple-icons/simple-icons/blob/develop/DISCLAIMER.md

export interface BrandData {
	title: string
	/** Brand color, hex without '#'. */
	hex: string
	/** Single path in a 24×24 viewBox, drawn filled. */
	path: string
	license?: string
}

export const SIMPLE_ICONS_VERSION = ${q(siVersion)}

export const BRANDS: Record<string, BrandData> = {
${Object.entries(brands)
	.map(([slug, b]) => `\t${q(slug)}: { title: ${q(b.title)}, hex: ${q(b.hex)}, path: ${q(b.path)}${b.license ? `, license: ${q(b.license)}` : ''} },`)
	.join('\n')}
}
`

const glyphsTs = `// GENERATED by scripts/build-icons.ts from lucide@${lucideVersion} — do not edit.
// Lucide is ISC licensed: Copyright (c) Lucide Icons and Contributors; portions
// derived from Feather (MIT, Copyright (c) 2013-present Cole Bemis).
// https://github.com/lucide-icons/lucide/blob/main/LICENSE

export const LUCIDE_VERSION = ${q(lucideVersion)}

/** lucide icon nodes (24×24, stroked) by kebab name. */
export const GLYPHS: Record<string, [tag: string, attrs: Record<string, string | number>][]> = {
${Object.entries(glyphs)
	.map(([name, node]) => `\t${q(name)}: [${node.map(([tag, a]) => `[${q(tag)}, ${objLit(a)}]`).join(', ')}],`)
	.join('\n')}
}
`

writeFileSync(join(outDir, 'brands.ts'), brandsTs)
writeFileSync(join(outDir, 'glyphs.ts'), glyphsTs)

// ── docs table (between markers in docs/ICONS.md) ───────────────────
try {
	const doc = readFileSync(docsPath, 'utf8')
	const start = '<!-- icons:start -->'
	const end = '<!-- icons:end -->'
	const a = doc.indexOf(start)
	const b = doc.indexOf(end)
	if (a >= 0 && b > a) {
		const row = (e: (typeof CATALOG)[number]) => {
			const src = e.slug && brands[e.slug] ? `simple-icons \`${e.slug}\`${brands[e.slug].license ? ` (${brands[e.slug].license})` : ''}` : `lucide \`${e.glyph}\`${e.slug || e.badge ? ` + badge` : ''}`
			return `| \`${e.name}\` | ${e.label} | ${(e.aliases ?? []).map((x) => `\`${x}\``).join(', ')} | ${src} |`
		}
		const table = ['| Name | Label | Aliases | Drawn from |', '|---|---|---|---|', ...CATALOG.map(row)].join('\n')
		const body = `\n_${CATALOG.length} icons, generated by \`pnpm -F @octo-draw/core build:icons\` (simple-icons@${siVersion}, lucide@${lucideVersion})._\n\n${table}\n`
		writeFileSync(docsPath, doc.slice(0, a + start.length) + body + doc.slice(b))
	}
} catch {
	// docs are optional
}

console.log(`brands: ${Object.keys(brands).length}, glyphs: ${Object.keys(glyphs).length}, catalog: ${CATALOG.length}`)
if (fallbacks.length) console.log(`brand fallbacks (lucide glyph + badge):\n  ${fallbacks.join('\n  ')}`)
if (attributions.length) console.log(`non-CC0 brand licenses (list in NOTICE):\n  ${attributions.join('\n  ')}`)
