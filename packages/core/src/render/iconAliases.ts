const toPascal = (kebab: string) =>
	kebab
		.split(/[-_\s]+/)
		.filter(Boolean)
		.map((p) => p[0].toUpperCase() + p.slice(1))
		.join('')

/** Candidate PascalCase lucide export names for an icon name, best first. */
export function iconCandidates(name: string): string[] {
	const n = name.trim().toLowerCase()
	const bare = n.replace(/^(aws|gcp|azure)-/, '')
	return [n, ICON_ALIASES[n], bare, ICON_ALIASES[bare]].filter((c): c is string => !!c).map(toPascal)
}
