/**
 * Hand-curated icon catalog for architecture diagrams (Eraser-compatible
 * names). This file is the source of truth: `scripts/build-icons.ts` reads it
 * and vendors the path data into `data/*.ts`. Keep it free of imports so the
 * build script can load it with plain `node --experimental-strip-types`.
 *
 * - `brand` entries draw a simple-icons logo (`slug`). If the slug is missing
 *   from simple-icons or its per-icon license is not redistributable, the
 *   build falls back to the lucide `glyph` + `badge`.
 * - `glyph` entries draw a lucide glyph, optionally with a short text badge.
 *   AWS, Google Cloud and Azure service icons are glyph entries: the vendors'
 *   official icon sets can't be redistributed in an MIT package (docs/ICONS.md).
 *   Users can download them locally (`pnpm icons:fetch`); registered packs
 *   (`registerIconPack`) then take over these names at runtime.
 */

export type IconVendor = 'aws' | 'gcp' | 'azure'

export interface CatalogEntry {
	/** Canonical DSL name (kebab-case). */
	name: string
	label: string
	aliases?: string[]
	/** simple-icons slug, for brand logos. */
	slug?: string
	/** lucide icon (kebab-case): the glyph for generic/vendor icons, the fallback for brands. */
	glyph: string
	/** Short text drawn on a pill over the glyph (vendor services, brand fallbacks). */
	badge?: string
	vendor?: IconVendor
	/** Extra search words. */
	tags?: string[]
}

const brand = (name: string, slug: string, label: string, glyph: string, aliases?: string[], tags?: string[]): CatalogEntry => ({ name, slug, label, glyph, aliases, tags })
const aws = (svc: string, label: string, glyph: string, badge: string, aliases?: string[]): CatalogEntry => ({ name: `aws-${svc}`, label: `AWS ${label}`, glyph, badge, vendor: 'aws', aliases, tags: ['aws', 'amazon'] })
const gcp = (svc: string, label: string, glyph: string, badge: string, aliases?: string[]): CatalogEntry => ({ name: `gcp-${svc}`, label: `Google Cloud ${label}`, glyph, badge, vendor: 'gcp', aliases, tags: ['gcp', 'google'] })
const azure = (svc: string, label: string, glyph: string, badge: string, aliases?: string[]): CatalogEntry => ({ name: `azure-${svc}`, label: `Azure ${label}`, glyph, badge, vendor: 'azure', aliases, tags: ['azure', 'microsoft'] })
const generic = (name: string, label: string, glyph: string, aliases?: string[], tags?: string[]): CatalogEntry => ({ name, label, glyph, aliases, tags })

